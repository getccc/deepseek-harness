/** Every copy key the console can ask for. */
export type CopyKey = keyof typeof zh

/**
 * Whether a string is a key this console has copy for.
 *
 * A navigation entry the product ships carries its own copy key, and the tree
 * it comes from is stored data: an entry naming a key this build does not have
 * falls back to the words the row carries rather than rendering blank.
 * @param key - the candidate copy key.
 * @returns true when both dictionaries hold it.
 */
export function isCopyKey(key: string): key is CopyKey {
  return Object.hasOwn(zh, key)
}
